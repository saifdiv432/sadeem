export function detectLang() {
    const names = GLib.get_language_names();
    for (const name of names) {
        const base = name.split(".")[0].split("_")[0].toLowerCase();
        if (SUPPORTED_LANGUAGES.includes(base)) {
            return base;
        }
    }
    return "ar";
}

export function isRtl() {
    try {
        if (typeof global !== "undefined" && typeof Clutter !== "undefined" && Clutter.get_default_text_direction) {
            return Clutter.get_default_text_direction() === Clutter.TextDirection.RTL;
        }
    } catch (e) {
        // Fallback
    }
    return detectLang() === "ar";
}

export function t(key, params = {}) {
    const lang = detectLang();
    let text = (STRINGS[lang] && STRINGS[lang][key]) ||
               (STRINGS["en"] && STRINGS["en"][key]) ||
               key;

    for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll("{" + k + "}", String(v));
    }
    return text;
}
