export function getCurrentLang() {
    try {
        const langs = GLib.get_language_names();
        for (const l of langs) {
            const code = l.split(':')[0].split('.')[0].split('_')[0].split('@')[0].toLowerCase();
            if (code in STRINGS)
                return code;
        }
    } catch (_e) {}
    return 'en';
}

export function isRtl(langCode = null) {
    const lang = langCode || getCurrentLang();
    return lang === 'ar';
}

export function t(key, params = {}, langOverride = null) {
    const lang = langOverride && (langOverride in STRINGS) ? langOverride : getCurrentLang();
    let text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
    if (params && typeof params === 'object') {
        for (const [k, v] of Object.entries(params))
            text = text.replaceAll(`{${k}}`, String(v));
    }
    return text;
}
