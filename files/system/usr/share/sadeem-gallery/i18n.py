def t(key, **kwargs):
    val = STRINGS.get(LANG, STRINGS["ar"]).get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


def format_month_year(year, month):
    if LANG == "ar":
        m_name = MONTHS_AR[month] if 1 <= month <= 12 else str(month)
    else:
        m_name = MONTHS_EN[month] if 1 <= month <= 12 else str(month)
    return f"{m_name} {year}"
