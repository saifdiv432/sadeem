def t(key, **kwargs):
    val = STRINGS.get(LANG, STRINGS["ar"]).get(key) or STRINGS["en"].get(key, key)
    if kwargs:
        try:
            return val.format(**kwargs)
        except Exception:
            return val
    return val


def format_month_year(year, month):
    mlist = MONTHS.get(LANG, MONTHS["en"])
    mname = mlist[month] if 1 <= month <= 12 else str(month)
    if LANG == "ar":
        return f"{mname} {year}"
    elif LANG == "zh":
        return f"{year}年{mname}"
    return f"{mname} {year}"
