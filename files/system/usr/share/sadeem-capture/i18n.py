def t(key, **kwargs):
    bundle = STRINGS.get(LANG, STRINGS["ar"])
    pattern = bundle.get(key) or STRINGS["en"].get(key) or STRINGS["ar"].get(key, key)
    if kwargs:
        try:
            return pattern.format(**kwargs)
        except Exception:
            return pattern
    return pattern
