SUPPORTED_LANGUAGES = ("ar", "en", "fr", "es", "de", "tr", "ru", "pt", "it", "zh")


def detect_lang():
    for var in ("LC_ALL", "LC_MESSAGES", "LANGUAGE", "LANG"):
        val = os.environ.get(var, "")
        if val:
            code = val.split(":")[0].split(".")[0].split("_")[0].split("@")[0].lower()
            if code in SUPPORTED_LANGUAGES:
                return code
    return "ar"


LANG = detect_lang()


